import sys
from playwright.sync_api import sync_playwright
BASE = sys.argv[1].rstrip('/') + '/'
ok = True
def check(name, cond, extra=''):
    global ok
    print(('PASS ' if cond else 'FAIL ') + name + (' :: ' + str(extra)[:160] if (extra and not cond) else ''))
    ok &= bool(cond)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    # 1. no JS: plain page readable, KJV only
    ctx = b.new_context(java_script_enabled=False); pg = ctx.new_page(); pg.goto(BASE + 'd/2026-10-11/')
    t = pg.inner_text('body')
    check('nojs: KJV subheading', 'King James Version' in t and 'World English Bible' not in t)
    check('nojs: KJV text visible, WEB hidden', 'he maketh me to lie' in t.lower() and 'He makes me lie down' not in t)
    check('nojs: no toggle', pg.locator('.trtoggle').count() == 0)
    ctx.close()
    # 2. JS plain pages
    ctx = b.new_context(permissions=['clipboard-read', 'clipboard-write']); pg = ctx.new_page()
    for day, kjvs, webs in [('2026-10-11', 'he maketh me to lie', 'He makes me lie down'), ('2026-10-09', 'Cursed is every one that hangeth on a tree', 'Cursed is everyone who hangs on a tree'), ('2026-11-08', 'Wisdom is glorious, and never fadeth away', 'Wisdom is radiant and doesn')]:
        pg.goto(BASE + f'd/{day}/'); pg.wait_for_selector('.trtoggle')
        t = pg.inner_text('body').lower()
        check(f'{day} plain default KJV', kjvs.lower() in t and webs.lower() not in t)
        check(f'{day} KJV pressed', pg.get_attribute('.trtoggle button[data-tr=kjv]', 'aria-pressed') == 'true')
        pg.click('.trtoggle button[data-tr=web]'); t = pg.inner_text('body')
        check(f'{day} plain WEB text', webs.lower() in t.lower() and kjvs.lower() not in t.lower(), t[:200])
        check(f'{day} WEB subheading', 'World English Bible, Catholic Edition' in pg.inner_text('.sub') and 'King James' not in pg.inner_text('.sub'))
        check(f'{day} WEB footer PD note', 'trademark of eBible.org' in t)
        check(f'{day} meditation intact', pg.locator('h2:has-text("Meditation")').count() == 1 and pg.locator('blockquote').count() == 1)
        check(f'{day} url has tr=web', 'tr=web' in pg.url, pg.url)
        check(f'{day} localStorage', pg.evaluate("localStorage.getItem('dr-tr')") == 'web')
        check(f'{day} open-in-app link carries tr', 'tr=web' in pg.get_attribute('a[data-app]', 'href'))
        pg.reload(); pg.wait_for_selector('.trtoggle')
        check(f'{day} remembered after reload', webs.lower() in pg.inner_text('body').lower())
        pg.click('.trtoggle button[data-tr=kjv]')
        check(f'{day} back to KJV', kjvs.lower() in pg.inner_text('body').lower() and 'tr=web' not in pg.url)
    # 3. app view
    pg.evaluate("localStorage.clear()")
    pg.goto(BASE + '?date=2026-10-11'); pg.wait_for_selector('#reading h1'); pg.wait_for_selector('.trtoggle')
    t = pg.inner_text('#view')
    check('app default KJV', 'he maketh me to lie' in t.lower() and 'He makes me lie down' not in t)
    pg.click('#copytext'); clip = pg.evaluate('navigator.clipboard.readText()')
    check('app copy text KJV', 'King James Version' in clip and 'maketh me to lie' in clip and 'World English' not in clip, clip[:200])
    pg.click('.trtoggle button[data-tr=web]')
    check('app WEB visible', 'He makes me lie down' in pg.inner_text('#view'))
    check('app WEB subheading', 'World English Bible, Catholic Edition' in pg.inner_text('.sub'))
    pg.click('#copytext'); clip = pg.evaluate('navigator.clipboard.readText()')
    check('app copy text WEB', 'World English Bible, Catholic Edition' in clip and 'He makes me lie down' in clip and 'maketh me' not in clip and 'In this mountain, the LORD of Armies' in clip, clip[:300])
    check('app copy text includes meditation + link', 'Meditation' in clip and 'tr=web' in clip.splitlines()[-1], clip[-200:])
    pg.click('#copylink'); link = pg.evaluate('navigator.clipboard.readText()')
    check('app copy link has tr=web', link.endswith('?date=2026-10-11&tr=web'), link)
    pg.click('#next'); pg.wait_for_function("document.title.includes('2026-10-12')||location.search.includes('2026-10-12')")
    check('app next keeps tr', 'tr=web' in pg.url and pg.evaluate("document.documentElement.dataset.tr") == 'web', pg.url)
    pg.click('.trtoggle button[data-tr=kjv]'); pg.click('#copylink'); link = pg.evaluate('navigator.clipboard.readText()')
    check('app copy link KJV has no tr', 'tr=' not in link, link)
    ctx.close()
    # 4. shared link opens in WEB in a fresh browser context (no stored preference)
    ctx = b.new_context(); pg = ctx.new_page(); pg.goto(BASE + '?date=2026-11-08&tr=web'); pg.wait_for_selector('#reading h1')
    t = pg.inner_text('#view')
    check('shared link opens in WEB (Wisdom)', 'Wisdom is radiant' in t and 'glorious' not in t.split('Psalm')[0], t[:200])
    pg.goto(BASE + '?date=2026-11-08'); pg.wait_for_selector('#reading h1')
    check('fresh no-param link default KJV', 'Wisdom is glorious' in pg.inner_text('#view'))
    b.close()
print('ALL PASS' if ok else 'SOME FAILED'); sys.exit(0 if ok else 1)
